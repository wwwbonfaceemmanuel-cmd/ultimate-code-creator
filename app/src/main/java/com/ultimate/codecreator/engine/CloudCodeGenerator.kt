package com.ultimate.codecreator.engine

import com.ultimate.codecreator.model.CloudEndpoint
import com.ultimate.codecreator.model.CloudGenerationException
import com.ultimate.codecreator.model.GenerationResult
import com.ultimate.codecreator.model.GenerationSource
import com.ultimate.codecreator.model.SupportedLanguage
import kotlinx.coroutines.suspendCancellableCoroutine
import okhttp3.Call
import okhttp3.Callback
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import okhttp3.Response
import org.json.JSONArray
import org.json.JSONObject
import java.io.IOException
import kotlin.coroutines.resume
import kotlin.coroutines.resumeWithException

/** Generates code via a cloud chat-completions API. */
interface CloudGenerator {
    suspend fun generate(prompt: String, language: SupportedLanguage, endpoint: CloudEndpoint): GenerationResult
}

/**
 * OpenAI-compatible chat-completions client (works with OpenAI, OpenRouter, Groq,
 * and any compatible endpoint). Sends only the instruction and target language.
 * The API key is used solely for the Authorization header and never logged.
 */
class OpenAiCloudGenerator(private val client: OkHttpClient) : CloudGenerator {

    override suspend fun generate(prompt: String, language: SupportedLanguage, endpoint: CloudEndpoint): GenerationResult {
        require(prompt.isNotBlank()) { "Enter an instruction first." }
        val request = buildRequest(prompt, language, endpoint)
        val response = try {
            client.newCall(request).await()
        } catch (exception: IOException) {
            throw CloudGenerationException("Could not reach the cloud provider. Check your connection and try again.", exception)
        }
        response.use {
            val body = it.body?.string().orEmpty()
            if (!it.isSuccessful) throw CloudGenerationException(mapHttpError(it.code))
            return parseCompletion(body, prompt, language, endpoint.model)
        }
    }

    private fun buildRequest(prompt: String, language: SupportedLanguage, endpoint: CloudEndpoint): Request {
        val payload = JSONObject()
            .put("model", endpoint.model)
            .put("temperature", 0.2)
            .put(
                "messages", JSONArray()
                    .put(JSONObject().put("role", "system").put("content", systemPrompt(language)))
                    .put(JSONObject().put("role", "user").put("content", prompt))
            )
        return Request.Builder()
            .url("${endpoint.baseUrl.trimEnd('/')}/chat/completions")
            .header("Authorization", "Bearer ${endpoint.apiKey}")
            .header("Content-Type", "application/json")
            .header("Accept", "application/json")
            .header("X-Title", "Ultimate Code Creator")
            .post(payload.toString().toRequestBody(JSON_MEDIA))
            .build()
    }

    private fun systemPrompt(language: SupportedLanguage): String =
        "You are a precise code generator. Respond with a single fenced code block in ${language.displayName} " +
            "that implements the user's request. Include brief inline comments where helpful. Do not include " +
            "explanations outside the code block. Never invent credentials, and avoid unsafe or destructive operations " +
            "unless explicitly requested. If the request is ambiguous, choose a sensible, minimal implementation."

    private fun parseCompletion(body: String, prompt: String, language: SupportedLanguage, model: String): GenerationResult {
        val content = try {
            JSONObject(body)
                .getJSONArray("choices")
                .getJSONObject(0)
                .getJSONObject("message")
                .getString("content")
        } catch (exception: Exception) {
            throw CloudGenerationException("The provider returned an unexpected response.", exception)
        }
        val code = extractCode(content).take(MAX_CODE_LENGTH)
        if (code.isBlank()) throw CloudGenerationException("The provider returned no code.")
        return GenerationResult(
            code = code,
            intentDetected = prompt.trim().take(60).ifEmpty { "AI generation" },
            explanation = "Generated by $model via cloud AI. Review carefully before use — AI output may be incorrect or unsafe.",
            language = language,
            isTemplateFallback = false,
            confidence = 0.6f,
            source = GenerationSource.CLOUD_AI,
            model = model
        )
    }

    private fun mapHttpError(code: Int): String = when (code) {
        401, 403 -> "Authentication failed. Check your API key in Settings."
        404 -> "Endpoint or model not found. Check the base URL and model in Settings."
        408, 504 -> "The provider timed out. Try again."
        429 -> "The provider rate-limited the request or your quota is exhausted."
        in 500..599 -> "The provider had a server error. Try again later."
        else -> "Cloud request failed (HTTP $code)."
    }

    companion object {
        const val MAX_CODE_LENGTH = 200_000
        private val JSON_MEDIA = "application/json; charset=utf-8".toMediaType()
        private val FENCE = Regex("```[a-zA-Z0-9_+.-]*\\r?\\n([\\s\\S]*?)```")

        /** Pull the first fenced code block if present; otherwise use the trimmed content. */
        fun extractCode(content: String): String {
            val fenced = FENCE.find(content)
            if (fenced != null) return fenced.groupValues[1].trim()
            return content.trim().removePrefix("```").removeSuffix("```").trim()
        }
    }
}

private suspend fun Call.await(): Response = suspendCancellableCoroutine { continuation ->
    continuation.invokeOnCancellation { runCatching { cancel() } }
    enqueue(object : Callback {
        override fun onFailure(call: Call, e: IOException) {
            if (continuation.isCancelled) return
            continuation.resumeWithException(e)
        }

        override fun onResponse(call: Call, response: Response) {
            continuation.resume(response)
        }
    })
}
